_files: dict[str, Any] = {}


def load(rel: str) -> Any:
    """A results file, by its path under results/ (JSON, or JSONL as a list)."""
    if rel not in _files:
        text = (RESULTS / rel).read_text(encoding="utf-8")
        if rel.endswith(".jsonl"):
            _files[rel] = [json.loads(x) for x in text.splitlines() if x]
        else:
            _files[rel] = json.loads(text)
    return _files[rel]


def lookup(obj: Any, path: str) -> Any:
    """`/`-separated; a key that itself contains `/` (a run named model/design) is matched by
    joining parts until a key is found."""
    parts = path.split("/") if path else []
    i = 0
    while i < len(parts):
        if isinstance(obj, list):
            obj = obj[int(parts[i])]
            i += 1
            continue
        for j in range(i + 1, len(parts) + 1):
            key = "/".join(parts[i:j])
            if key in obj:
                obj, i = obj[key], j
                break
        else:
            raise KeyError(f"no {parts[i]!r} in path {path!r}")
    return obj


