def render(template: Path, values: dict[str, str]) -> str:
    def sub(m: re.Match) -> str:
        name = m.group(1)
        if name.startswith("table:"):
            return TABLES[name.split(":", 1)[1]]()
        if name not in values:
            raise KeyError(f"{template.name}: {{{{{name}}}}} has no value in values.yaml")
        return values[name]

    return HEADER + PLACEHOLDER.sub(sub, template.read_text(encoding="utf-8"))


def render_all() -> dict[Path, str]:
    spec = yaml.safe_load(VALUES.read_text(encoding="utf-8"))
    values = resolve_values(spec)
    used = {n for t, _ in DOCS for n in PLACEHOLDER.findall(t.read_text(encoding="utf-8"))}
    in_exprs = {
        n for v in (spec.get("values") or {}).values() for n in NAME.findall(v.get("expr", ""))
    }
    unused = set(values) - used - in_exprs
    if unused:
        print(f"note: values defined but not used: {sorted(unused)}")
    pending = sorted(n for n, v in values.items() if v == TBD)
    if pending:
        print(f"note: {len(pending)} values pending (rendered TBD): {pending}")
    return {out: render(t, values) for t, out in DOCS}


def problems_in(rendered: dict[Path, str]) -> list[str]:
    found = [
        f"typed number (not from a results file): {x}" for t, _ in DOCS for x in typed_literals(t)
    ]
    found += [x for out, text in rendered.items() for x in tables_without_source(text, out.name)]
    return found


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    rendered = render_all()
    problems = problems_in(rendered)
    if args.check:
        problems += [
            f"{out.name} differs from a fresh render: run scripts/90_readme.py"
            for out, text in rendered.items()
            if not out.exists() or out.read_text(encoding="utf-8") != text
        ]
        if problems:
            sys.exit("\n".join(problems))
        print("README.md and TECHNICAL_REPORT.md match the results files")
        return
    if problems:
        sys.exit("\n".join(problems))
    for out, text in rendered.items():
        out.write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote {out.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
