def typed_literals(template: Path) -> list[str]:
    spec = yaml.safe_load(VALUES.read_text(encoding="utf-8"))
    allowed = set(spec.get("allowed_literals") or [])
    text = PLACEHOLDER.sub("", template.read_text(encoding="utf-8"))
    text = re.sub(r"```.*?```", "", text, flags=re.S)
    text = re.sub(r"`[^`\n]*`", "", text)  # code spans: settings, versions, paths
    text = re.sub(r"\]\([^)]*\)", "]", text)  # link targets
    found = []
    for i, line in enumerate(text.splitlines(), 1):
        for m in LITERAL.finditer(line):
            if m.group(0) not in allowed:
                found.append(f"{template.name} line {i}: {m.group(0)!r} in: {line.strip()[:80]}")
    return found


def tables_without_source(text: str, name: str) -> list[str]:
    """Tables (runs of lines starting with `|`, outside code blocks) not followed, after
    any blank lines, by a line with `Source:` and something after it."""
    lines = text.splitlines()
    problems, i, in_code = [], 0, False
    while i < len(lines):
        if lines[i].lstrip().startswith("```"):
            in_code = not in_code
        elif not in_code and TABLE_ROW.match(lines[i]):
            start = i
            while i < len(lines) and TABLE_ROW.match(lines[i]):
                i += 1
            j = i
            while j < len(lines) and not lines[j].strip():
                j += 1
            if j == len(lines) or not SOURCE_LINE.search(lines[j]):
                problems.append(f"{name} line {start + 1}: a table without a Source: line")
            continue
        i += 1
    return problems


