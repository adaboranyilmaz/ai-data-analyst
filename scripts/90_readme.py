# Checks


def typed_literals(template: Path) -> list[str]:
    spec = yaml.safe_load(VALUES.read_text(encoding="utf-8"))
    allowed = set(spec.get("allowed_literals") or [])
    text = PLACEHOLDER.sub("", template.read_text(encoding="utf-8"))
    text = re.sub(r"```.*?```", "", text, flags=re.S)
    text = re.sub(r"`[^`\n]*`", "", text)  # code spans: settings, versions, paths
    text = re.sub(r"\]\([^)]*\)", "]", text)  # link targets
    found = []
    for i, line in enumerate(text.splitlines(), 1):
        for m in LITERAL.finditer(line):
            if m.group(0) not in allowed:
                found.append(f"{template.name} line {i}: {m.group(0)!r} in: {line.strip()[:80]}")
    return found


def tables_without_source(text: str, name: str) -> list[str]:
    """Tables (runs of lines starting with `|`, outside code blocks) not followed, after
    any blank lines, by a line with `Source:` and something after it."""
    lines = text.splitlines()
    problems, i, in_code = [], 0, False
    while i < len(lines):
        if lines[i].lstrip().startswith("```"):
            in_code = not in_code
        elif not in_code and TABLE_ROW.match(lines[i]):
            start = i
            while i < len(lines) and TABLE_ROW.match(lines[i]):
                i += 1
            j = i
            while j < len(lines) and not lines[j].strip():
                j += 1
            if j == len(lines) or not SOURCE_LINE.search(lines[j]):
                problems.append(f"{name} line {start + 1}: a table without a Source: line")
            continue
        i += 1
    return problems


# --------------------------------------------------------------------------------------


def render(template: Path, values: dict[str, str]) -> str:
    def sub(m: re.Match) -> str:
        name = m.group(1)
        if name.startswith("table:"):
            return TABLES[name.split(":", 1)[1]]()
        if name not in values:
            raise KeyError(f"{template.name}: {{{{{name}}}}} has no value in values.yaml")
        return values[name]

    return HEADER + PLACEHOLDER.sub(sub, template.read_text(encoding="utf-8"))


def render_all() -> dict[Path, str]:
    spec = yaml.safe_load(VALUES.read_text(encoding="utf-8"))
    values = resolve_values(spec)
    used = {n for t, _ in DOCS for n in PLACEHOLDER.findall(t.read_text(encoding="utf-8"))}
    in_exprs = {
        n for v in (spec.get("values") or {}).values() for n in NAME.findall(v.get("expr", ""))
    }
    unused = set(values) - used - in_exprs
    if unused:
        print(f"note: values defined but not used: {sorted(unused)}")
    pending = sorted(n for n, v in values.items() if v == TBD)
    if pending:
        print(f"note: {len(pending)} values pending (rendered TBD): {pending}")
    return {out: render(t, values) for t, out in DOCS}


def problems_in(rendered: dict[Path, str]) -> list[str]:
    found = [
        f"typed number (not from a results file): {x}" for t, _ in DOCS for x in typed_literals(t)
    ]
    found += [x for out, text in rendered.items() for x in tables_without_source(text, out.name)]
    return found


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    rendered = render_all()
    problems = problems_in(rendered)
    if args.check:
        problems += [
            f"{out.name} differs from a fresh render: run scripts/90_readme.py"
            for out, text in rendered.items()
            if not out.exists() or out.read_text(encoding="utf-8") != text
        ]
        if problems:
            sys.exit("\n".join(problems))
        print("README.md and TECHNICAL_REPORT.md match the results files")
        return
    if problems:
        sys.exit("\n".join(problems))
    for out, text in rendered.items():
        out.write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote {out.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
